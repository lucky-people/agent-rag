def generate_variants(templates, target_count):
    """对模板进行变体扩展，达到目标数量"""
    results = list(templates)
    # 变体前缀
    prefixes = ["请问", "我想问问", "咨询一下", "想问下", "请教一下", "问一下", "请问一下", ""]
    # 变体后缀
    suffixes = ["", "呢", "啊", "呀", "？", "吗", "呢？"]
    # 同义词替换映射
    synonyms = [
        ("房东", "房主"), ("房东", "业主"), ("租客", "租户"), ("租客", "承租人"),
        ("租房", "租房子"), ("租房", "租个房"), ("退租", "退房"), ("退租", "不租了"),
        ("押金", "保证金"), ("合同", "协议"), ("怎么办", "怎么处理"),
        ("怎么办", "该怎么办"), ("合法吗", "违法吗"), ("合法吗", "合理吗"),
        ("能", "可以"), ("要", "需要"), ("吗", "么"),
    ]

    attempt = 0
    while len(results) < target_count and attempt < 5000:
        attempt += 1
        t = random.choice(templates)
        # 随机加前缀
        if random.random() < 0.4:
            t = random.choice(prefixes) + t
        # 随机加后缀
        if random.random() < 0.3:
            t = t + random.choice(suffixes)
        # 随机同义词替换
        if random.random() < 0.5:
            src, dst = random.choice(synonyms)
            if src in t:
                t = t.replace(src, dst, 1)
        if t not in results:
            results.append(t)

    return results[:target_count]


